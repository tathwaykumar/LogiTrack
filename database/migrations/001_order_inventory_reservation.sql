-- Phase 3B: record which warehouse supplied each product of an order.
--
-- Additive only: creates one new table and its indexes. No existing table,
-- column, constraint or row is modified, and no reservations are back-filled
-- for historical orders (their sourcing was never recorded).
--
-- Safe to re-run: every statement is guarded with IF NOT EXISTS.

BEGIN;

CREATE TABLE IF NOT EXISTS public.order_inventory_reservation (
    reservation_id integer GENERATED BY DEFAULT AS IDENTITY,
    order_id integer NOT NULL,
    warehouse_id integer NOT NULL,
    product_id integer NOT NULL,
    reserved_quantity integer NOT NULL,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT order_inventory_reservation_pkey PRIMARY KEY (reservation_id),
    CONSTRAINT chk_reservation_quantity CHECK ((reserved_quantity > 0)),
    -- One row per order/warehouse/product; quantities from the same source are summed.
    CONSTRAINT uq_reservation_order_warehouse_product UNIQUE (order_id, warehouse_id, product_id),
    CONSTRAINT fk_reservation_order FOREIGN KEY (order_id) REFERENCES public.orders(order_id),
    CONSTRAINT fk_reservation_warehouse FOREIGN KEY (warehouse_id) REFERENCES public.warehouse(warehouse_id),
    CONSTRAINT fk_reservation_product FOREIGN KEY (product_id) REFERENCES public.product(product_id),
    -- A reservation can only exist for a product that is actually on the order.
    CONSTRAINT fk_reservation_order_item FOREIGN KEY (order_id, product_id)
        REFERENCES public.order_item(order_id, product_id)
);

-- Lookups by order are served by the unique constraint's leading column.
CREATE INDEX IF NOT EXISTS idx_reservation_warehouse_product
    ON public.order_inventory_reservation USING btree (warehouse_id, product_id);

CREATE INDEX IF NOT EXISTS idx_reservation_product
    ON public.order_inventory_reservation USING btree (product_id);

COMMIT;
